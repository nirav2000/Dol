import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {chooseAdaptiveNumber} from '../adaptive.mjs';
const seed=Array.from({length:10000},(_,i)=>i/10000).find(r=>chooseAdaptiveNumber({stage:'foundation',limit:64,random:()=>r})===12);
assert.notEqual(seed,undefined);
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
fs.mkdirSync('artifacts',{recursive:true});
try{
 const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:3,isMobile:true,hasTouch:true});
 await context.addInitScript(seed=>{Math.random=()=>seed;localStorage.setItem('dol-focus-mode-v1','true');localStorage.setItem('dol-focus-immersive-opt-in-v2','true');localStorage.setItem('dol-auto-difficulty-v1','false');localStorage.setItem('dol-round-tools-v1',JSON.stringify({autoNext:false}));localStorage.setItem('dol-learning-settings-v2',JSON.stringify({mode:'guided',stage:'foundation',limit:64,duration:60,sound:false,showCount:true}));},seed);
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TEST_BASE_URL||'http://127.0.0.1:8000/',{waitUntil:'networkidle'});
 assert.equal(await page.locator('#startButton').isVisible(),true,'Ready screen must show Start round');
 await page.locator('#startButton').click();
 await page.locator('#mobileEntry').waitFor({state:'visible'});
 assert.equal(await page.locator('#mobileKeypad button').count(),12);
 assert.equal(await page.locator('#mobileKeypad [data-key="1"]').evaluate(e=>e.getBoundingClientRect().height>=56),true,'Key must be at least 56px tall');
 assert.equal(await page.locator('#mobileKeypad [data-key="action"]').textContent(),'×');
 assert.equal(await page.locator('#mobileKeypad [data-key="action"]').getAttribute('aria-label'),'Next factor');
 assert.notEqual(await page.locator('#pairInput').evaluate(e=>document.activeElement===e),true,'Native keyboard must not be focused');
 const target=Number(await page.locator('#numberValue').textContent());
 const digits=String(target).split('');
 await page.locator('#mobileKeypad [data-key="1"]').click();
 await page.locator('#mobileKeypad [data-key="action"]').click();
 assert.equal(await page.locator('#mobileKeypad [data-key="action"]').textContent(),'↵');
 for(const digit of digits)await page.locator('#mobileKeypad [data-key="'+digit+'"]').click();
 assert.equal(await page.locator('#mobileSecond').textContent(),String(target));
 await page.locator('#mobileKeypad [data-key="action"]').click();
 const debug=await page.evaluate(()=>({feedback:document.querySelector('#entryFeedback').textContent,input:document.querySelector('#pairInput').value,first:document.querySelector('#mobileFirst').textContent,second:document.querySelector('#mobileSecond').textContent,slots:document.querySelectorAll('#pairSlots .slot.solved').length,phase:document.querySelector('#playView').dataset.mobilePhase}));
 assert.ok(debug.feedback.includes('Correct') || (debug.phase==='finished' && debug.slots===1),JSON.stringify({target,...debug}));
 assert.equal(await page.locator('#mobileFirst').textContent(),'—');
 assert.equal(await page.locator('#pairSlots .slot.solved').count(),1);
 if(debug.phase!=='finished')assert.equal(await page.locator('#mobileKeypad [data-key="action"]').textContent(),'×');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'No horizontal overflow');
 await page.screenshot({path:'artifacts/mobile-game-390.png',fullPage:true});
 if(await page.locator('#activePanel').isVisible())await page.locator('#finishButton').click();
 await page.locator('#mobileKeypad [data-key="action"]').waitFor({state:'visible'});
 assert.equal(await page.locator('#mobileKeypad [data-key="action"]').isVisible(),true);
 assert.match(await page.locator('#mobileKeypad [data-key="action"]').textContent(),/Next question/);
 assert.equal(await page.locator('#mobileEntry').evaluate(el=>el.parentElement?.id),'finishedPanel','review action stays in the reading flow');
 assert.notEqual(await page.locator('#mobileEntry').evaluate(el=>getComputedStyle(el).position),'fixed');
 await page.locator('#mobileKeypad [data-key="action"]').scrollIntoViewIfNeeded();
 const actionBox=await page.locator('#mobileKeypad [data-key="action"]').boundingBox();
 assert.ok(actionBox && actionBox.y>=0 && actionBox.y+actionBox.height<=844,'Next remains accessible below the review');
 assert.equal(await page.locator('#startButton').isVisible(),false);
 await page.locator('#mobileKeypad [data-key="action"]').click();
 assert.equal(await page.locator('#activePanel').isVisible(),true,'Next question must start from mobile button');
 await page.locator('#finishButton').click();
 await page.keyboard.press('Enter');
 assert.equal(await page.locator('#activePanel').isVisible(),true,'Enter must start next question');
 await page.setViewportSize({width:320,height:680});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'No horizontal overflow at 320');
 await page.screenshot({path:'artifacts/mobile-game-320.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Mobile custom keypad, action-key rotation, scoring, focus and responsive widths passed');
 await context.close();
}finally{await browser.close();}
