import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.addInitScript(()=>localStorage.setItem('dol-focus-mode-v1','false'));
await page.goto('http://127.0.0.1:8000/',{waitUntil:'networkidle',timeout:45000});
await page.waitForSelector('[data-mode="guided"]');
assert.equal(await page.locator('#readyPanel').isVisible(),true);
await page.locator('#startButton').click();
const target=Number(await page.locator('#numberValue').textContent());
assert.ok(target>=2&&target<=24);
await page.locator('#factorButtons button').first().click();
await page.locator('#hintNext').click();
assert.match(await page.locator('#hintLevel').textContent(),/1 of 4/);
await page.locator('#pairInput').fill('1x'+target);
await page.locator('#addButton').click();
if(await page.locator('#activePanel').isVisible()){
  assert.match(await page.locator('#foundHeading').textContent(),/1 found/);
  await page.locator('#finishButton').click();
}
assert.equal(await page.locator('#finishedPanel').isVisible(),true);
await page.locator('[data-view="learn"]').click();
assert.equal(await page.locator('#topicList .topic').count()>=20,true);
assert.equal(await page.locator('.glossary-grid article').count()>=15,true);
await page.locator('[data-view="progress"]').click();
assert.equal(await page.locator('#statRounds').textContent(),'1');
assert.equal(await page.locator('#insightGrid .fact-cell').count(),144);
assert.equal(await page.locator('#conceptList .concept-button').count()>0,true);
await page.locator('#insightGrid .fact-cell').first().click();
assert.match(await page.locator('#factDetail').textContent(),/1 × 1/);
await page.locator('#conceptList .concept-button').first().click();
assert.match(await page.locator('#conceptDetail').textContent(),/recorded events/);
await page.screenshot({path:'browser-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.locator('[data-view="play"]').click();
await page.locator('[data-mode="practice"]').click();
await page.locator('#startButton').click();
assert.equal(await page.locator('#helpSection').isVisible(),false);
await page.locator('#helpToggle').click();
assert.equal(await page.locator('#helpSection').isVisible(),true);
await page.locator('#finishButton').click();
await page.locator('[data-mode="timed"]').click();
await page.locator('#startButton').click();
assert.equal(await page.locator('#pauseButton').isVisible(),true);
await page.locator('#pauseButton').click();
assert.equal(await page.locator('#pausedOverlay').isVisible(),true);
await page.locator('#pauseButton').click();
await page.screenshot({path:'browser-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);
await browser.close();
console.log('Browser smoke: guided hints, scoring, learn, progress, timed pause, mobile passed');
